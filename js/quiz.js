// 今出している問題の番号（0・1・2）。まだ問題を出していないときは -1
let q = -1;


// ===== 問題ボタンを押したとき =====
$("#question_btn").on("click", function () {
  // 問題をランダムに決める（0:問題1 1:問題2 2:問題3）
  q = Math.floor(Math.random() * 3);

  // 前のコメントを消す
  $("#result").text("");
  // 選択肢を表示する（最初だけ hidden が付いている）
  $(".choice_section").removeClass("hidden");
  // 前の問題で選んだ色を消す
  $(".choice_section button").removeClass("selected");

  // 問題文と選択肢を表示（問題ごとに選択肢が変わる）
  if (q === 0) {
    // 問題1：質問内容について
    $("#question").text("どんな質問を聞いてみる？");
    $("#btn1").text("「AIを使った仕事をしたいです。AI部門はありますか？」");
    $("#btn2").text("「有給休暇は年間何日取得できますか？」");
    $("#btn3").text("「今、チームではどんな新しい技術に取り組んでいますか？」");
  } else if (q === 1) {
    // 問題2：他の人が質問しているとき
    $("#question").text("他の受講生が質問している間、どうしている？");
    $("#btn1").text("今は自分のターンではないので休憩する");
    $("#btn2").text("質問している人と答える人の方を向き、メモを取る");
    $("#btn3").text("次に当ててもらえるよう、ずっと手を挙げて待つ");
  } else {
    // 問題3：時間が残り少ないとき
    $("#question").text("質疑応答の残り時間はあと少し。聞きたいことが3つある。どうする？");
    $("#btn1").text("止められるまで3つ全部続けて聞く");
    $("#btn2").text("1つに絞って短く聞き、残りは進行役に時間があるか確認する");
    $("#btn3").text("時間がないので、今回は手を挙げない");
  }
});


// ===== 選択肢1を押したとき =====
$("#btn1").on("click", function () {
  if (q === -1) {
    $("#result").text("先に「問題を出す」を押してください");
  } else if (q === 0) {
    $("#result").text("関心は伝わるが自分ファーストにも見えます。事前リサーチも忘れずに。");
  } else if (q === 1) {
    $("#result").text("他の人のことに無関心なように見えます。");
  } else {
    $("#result").text("熱意は伝わりますが、時間への意識が薄い印象にも見えます。");
  }
});


// ===== 選択肢2を押したとき =====
$("#btn2").on("click", function () {
  if (q === -1) {
    $("#result").text("先に「問題を出す」を押してください");
  } else if (q === 0) {
    $("#result").text("大事な質問ですが、いきなり休み重視な姿勢にも見えます。");
  } else if (q === 1) {
    $("#result").text("人の話を大切にする姿勢が伝わります。気が緩みやすい時間ほど、実はよく見られています。");
  } else {
    $("#result").text("時間と他の参加者への気づかいが伝わります。");
  }
});


// ===== 選択肢3を押したとき =====
$("#btn3").on("click", function () {
  if (q === -1) {
    $("#result").text("先に「問題を出す」を押してください");
  } else if (q === 0) {
    $("#result").text("答えやすい聞き方で、相手の仕事に関心がある人だと映ります。");
  } else if (q === 1) {
    $("#result").text("積極的ですが、自分の番のことばかり考えているように見えます。");
  } else {
    $("#result").text("慎重な判断ですが、関心が伝わらないままになってしまいます。");
  }
});

// ===== どの選択肢でも、押したら色を付ける =====
$(".choice_section button").on("click", function () {
  $(".choice_section button").removeClass("selected");   // いったん全部の色を消す
  $(this).addClass("selected");                          // 押したボタンだけに色を付ける
  $("#result").hide().fadeIn(400); 
});